/**
 * Mind map storage.
 *
 * Persistence: one JSON file per map under
 * `<workspaceRoot>/.dailyflow/mindmaps/<id>.json`.
 *
 * We deliberately do NOT piggy-back on the v2 markdown repository:
 *  - mind maps are inherently graph data, not markdown;
 *  - the v2 repository is append-audit / conflict-resolved; we just need
 *    a single-document save with no concurrent writers in the UI today.
 *
 * Concurrency: the in-process write queue (`saveQueue`) serializes writes
 * per file. Two near-simultaneous saves can't interleave a half-written
 * JSON, but we do NOT add file-level locks for now because the UI is the
 * sole writer.
 *
 * Schema versioning (SPEC §2.2):
 *   - `version: 1` — pre-Topic-Space format. Read tolerantly, no rewrite.
 *   - `version: 2` — current. Adds `spaceId` and per-node `kind` / `tag`
 *     / `taskId`. Any PUT auto-bumps to v2. New creates write v2.
 */
import { promises as fs } from 'fs';
import path from 'path';
import { ulid } from 'ulid';
import { loadConfig } from './config.js';
import type { MindMap, MindMapInput, MindMapNode, MindMapEdge, MindMapNodeKind } from '../types/mindmap.js';
import { DEFAULT_MINDMAP_NODE_KIND } from '../types/mindmap.js';

/** Current schema version for new writes. Reads accept both 1 and 2. */
const SCHEMA_VERSION = 2 as const;

/** Maps older than this are still readable. */
const MIN_SUPPORTED_VERSION = 1 as const;

function getDir(): string {
  // loadConfig is async; we expose `getDir` only after the config resolves.
  // See `withDir` below.
  throw new Error('getDir called without workspaceRoot; use withDir');
}

async function withDir<T>(fn: (dir: string) => Promise<T>): Promise<T> {
  const config = await loadConfig();
  const dir = path.join(config.workspaceRoot, '.dailyflow', 'mindmaps');
  await fs.mkdir(dir, { recursive: true });
  return fn(dir);
}

function fileFor(dir: string, id: string): string {
  // id is generated by `ulid()` and is url-safe; no sanitisation needed.
  return path.join(dir, `${id}.json`);
}

const saveQueue = new Map<string, Promise<unknown>>();

async function readMapFile(filePath: string): Promise<MindMap> {
  const raw = await fs.readFile(filePath, 'utf-8');
  return JSON.parse(raw) as MindMap;
}

async function writeMapFile(filePath: string, map: MindMap): Promise<void> {
  // Serialize per file so concurrent updates don't interleave a half-written
  // document on disk.
  const previous = saveQueue.get(filePath) ?? Promise.resolve();
  const next = previous.then(() => fs.writeFile(filePath, JSON.stringify(map, null, 2), 'utf-8'));
  saveQueue.set(filePath, next.catch(() => undefined));
  await next;
}

/**
 * Fill default `kind` for any node that doesn't have one (SPEC §2.2:
 * "缺省 `kind === 'branch'` (兼容老节点)"). This is a pure function so
 * tests can pin its behavior.
 */
export function defaultNodeKind(node: MindMapNode): MindMapNode {
  if (node.kind) return node;
  return { ...node, kind: DEFAULT_MINDMAP_NODE_KIND };
}

/** Apply `defaultNodeKind` to every node in an array. */
function defaultNodeKinds(nodes: MindMapNode[]): MindMapNode[] {
  return nodes.map(defaultNodeKind);
}

function emptyMap(title: string, now: string, spaceId?: string): MindMap {
  const id = ulid();
  const rootId = ulid();
  const root: MindMapNode = {
    id: rootId,
    text: title || '中心主题',
    position: { x: 0, y: 0 },
    kind: 'root',
  };
  return {
    id,
    title: title || '未命名导图',
    rootId,
    nodes: [root],
    edges: [],
    version: SCHEMA_VERSION,
    ...(spaceId ? { spaceId } : {}),
    createdAt: now,
    updatedAt: now,
  };
}

export async function listMindMaps(): Promise<MindMap[]> {
  return withDir(async (dir) => {
    const entries = await fs.readdir(dir);
    const maps: MindMap[] = [];
    for (const entry of entries) {
      if (!entry.endsWith('.json')) continue;
      try {
        const map = await readMapFile(path.join(dir, entry));
        // Accept any supported version; unknown future versions are skipped
        // so a forward-incompatible change doesn't break the whole list.
        if (map && map.version >= MIN_SUPPORTED_VERSION && map.version <= SCHEMA_VERSION) {
          maps.push(map);
        }
      } catch (err) {
        // A corrupt file should not break the whole list. Log and skip.
        console.error(`[mindmaps] skip unreadable ${entry}:`, err);
      }
    }
    // Newest first by updatedAt.
    maps.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
    return maps;
  });
}

export async function getMindMap(id: string): Promise<MindMap | null> {
  return withDir(async (dir) => {
    const filePath = fileFor(dir, id);
    try {
      return await readMapFile(filePath);
    } catch (err: any) {
      if (err && err.code === 'ENOENT') return null;
      throw err;
    }
  });
}

export async function createMindMap(input: Partial<MindMapInput> = {}): Promise<MindMap> {
  const now = new Date().toISOString();
  const title = (input.title ?? '').trim() || '未命名导图';
  const map = emptyMap(title, now, input.spaceId);
  if (input.rootId) map.rootId = input.rootId;
  if (Array.isArray(input.nodes) && input.nodes.length > 0) {
    map.nodes = defaultNodeKinds(input.nodes);
    if (!map.nodes.find((n) => n.id === map.rootId) && map.nodes[0]) {
      map.rootId = map.nodes[0].id;
    }
  }
  if (Array.isArray(input.edges)) map.edges = input.edges;
  return withDir(async (dir) => {
    await writeMapFile(fileFor(dir, map.id), map);
    return map;
  });
}

export interface MindMapUpdate {
  title?: string;
  rootId?: string;
  nodes?: MindMapNode[];
  edges?: MindMapEdge[];
  /**
   * v2: allow the route (or TopicSpace) to set the reverse link. If
   * omitted, the existing `spaceId` is preserved.
   */
  spaceId?: string | null;
}

export async function updateMindMap(id: string, patch: MindMapUpdate): Promise<MindMap | null> {
  const now = new Date().toISOString();
  return withDir(async (dir) => {
    const filePath = fileFor(dir, id);
    let existing: MindMap;
    try {
      existing = await readMapFile(filePath);
    } catch (err: any) {
      if (err && err.code === 'ENOENT') return null;
      throw err;
    }
    // Any PUT auto-bumps to the current schema version (SPEC §3.3).
    // The resulting `nodes` array gets `kind: 'branch'` defaulted on
    // any node missing one — including nodes we inherited from the
    // v1 file on disk, not just the ones the client sent. This is
    // what makes the file truly forward-migrated to v2 shape.
    const baseNodes = patch.nodes !== undefined ? patch.nodes : existing.nodes;
    const next: MindMap = {
      ...existing,
      title: patch.title !== undefined ? patch.title : existing.title,
      rootId: patch.rootId !== undefined ? patch.rootId : existing.rootId,
      nodes: defaultNodeKinds(baseNodes),
      edges: patch.edges !== undefined ? patch.edges : existing.edges,
      version: SCHEMA_VERSION,
      updatedAt: now,
    };
    if (patch.spaceId !== undefined) {
      if (patch.spaceId === null) {
        delete next.spaceId;
      } else {
        next.spaceId = patch.spaceId;
      }
    } else if (existing.spaceId) {
      // Preserve existing reverse link.
      next.spaceId = existing.spaceId;
    }
    await writeMapFile(filePath, next);
    return next;
  });
}

export async function deleteMindMap(id: string): Promise<boolean> {
  return withDir(async (dir) => {
    const filePath = fileFor(dir, id);
    try {
      await fs.unlink(filePath);
      return true;
    } catch (err: any) {
      if (err && err.code === 'ENOENT') return false;
      throw err;
    }
  });
}

/**
 * Update a single node in a mindmap without round-tripping the full
 * `nodes` array. Returns the updated MindMap (with version bump, kind
 * defaulting, and updatedAt). Returns `null` if the map or node does
 * not exist.
 *
 * The patch is shallow: it overwrites the named keys on the matching
 * node. To delete an optional field, set it to `undefined` in the
 * patch; the implementation strips the key from the stored object so
 * the file on disk reflects the cleared state.
 *
 * Rationale: the route handlers (promote-to-task, link-task, repair)
 * only need to flip one node's kind/taskId. The existing `updateMindMap`
 * would force the caller to send back the entire `nodes` array, which
 * is both wasteful and a footgun (any node dropped on the way would
 * be silently deleted from the file).
 */
export async function updateNodeInMindMap(
  mindmapId: string,
  nodeId: string,
  patch: Partial<MindMapNode>,
): Promise<MindMap | null> {
  const now = new Date().toISOString();
  return withDir(async (dir) => {
    const filePath = fileFor(dir, mindmapId);
    let existing: MindMap;
    try {
      existing = await readMapFile(filePath);
    } catch (err: any) {
      if (err && err.code === 'ENOENT') return null;
      throw err;
    }
    const idx = existing.nodes.findIndex(n => n.id === nodeId);
    if (idx === -1) return null;
    // Apply the patch, dropping any keys explicitly set to undefined so
    // the cleared state survives a round-trip.
    const merged: MindMapNode = { ...existing.nodes[idx] };
    for (const [k, v] of Object.entries(patch)) {
      if (v === undefined) {
        delete (merged as any)[k];
      } else {
        (merged as any)[k] = v;
      }
    }
    // Re-default `kind` if the patch wiped it.
    if (!merged.kind) merged.kind = DEFAULT_MINDMAP_NODE_KIND;
    const nextNodes = existing.nodes.slice();
    nextNodes[idx] = merged;
    const next: MindMap = {
      ...existing,
      nodes: nextNodes,
      version: SCHEMA_VERSION,
      updatedAt: now,
    };
    await writeMapFile(filePath, next);
    return next;
  });
}

/**
 * Walk the parent chain of a node and collect `kind: 'tag'` labels in
 * root-to-leaf order. Used by `appendTaskToMarkdown` (Topic Spaces
 * Phase 3) to inherit tag labels from the source mindmap.
 *
 * Returns an empty array if the mindmap or node does not exist, or if
 * no ancestor is a tag node. Multiple tag ancestors are deduplicated
 * (case-insensitive) while preserving first-occurrence order.
 *
 * Edges are interpreted as parent → child (`source` is the parent).
 * This matches the convention used everywhere else in the codebase
 * (see `MindMapEdge` in `types/mindmap.ts`).
 */
export function getInheritedTagsFromMap(
  map: MindMap,
  nodeId: string,
): string[] {
  // Build a parent map once: child -> parent (first occurrence wins;
  // a multi-parent cycle is treated as a no-parent for that child).
  const parentOf = new Map<string, string>();
  for (const edge of map.edges) {
    if (!parentOf.has(edge.target)) parentOf.set(edge.target, edge.source);
  }

  // Walk from node up to the root, collecting tag nodes. The root is
  // the node with `kind: 'root'` (or the node the mindmap declares as
  // `rootId` if no node carries the discriminator).
  //
  // We collect in leaf-to-root order, then reverse at the end so the
  // returned list reads root-to-leaf. That's the order that maps onto
  // a natural "broader → narrower" tag hierarchy when the markdown
  // line is rendered, and it also matches the order the spec example
  // (SPEC §2) shows for a single inheritance path.
  const rootId = map.rootId;
  const seen = new Set<string>();
  const out: string[] = [];
  let cur: string | undefined = nodeId;
  // Cycle guard: cap the walk at nodes.length so a malformed graph
  // can't spin forever.
  let safety = map.nodes.length + 1;
  while (cur && safety-- > 0) {
    if (cur === rootId) break; // reached the root; stop without including it
    const node = map.nodes.find(n => n.id === cur);
    if (!node) break;
    if (node.kind === 'tag' && node.tag) {
      const key = node.tag.toLowerCase();
      if (!seen.has(key)) {
        seen.add(key);
        out.push(node.tag);
      }
    }
    cur = parentOf.get(cur);
  }
  out.reverse();
  return out;
}

